    def _on_segment_row_clicked(self, row, column):
        if row < 0 or row >= len(self.segments):
            return
        segment = self.segments[row]
        dialog = SegmentDetailDialog(
            segment,
            self.track_a,
            self.track_b,
            self.name_a,
            self.name_b,
            parent=self,
        )
        dialog.point_selected.connect(self.segment_point_selected)
        dialog.exec()

    def _populate_coach_insights(self):
        """Import the coach insights generator from core.analyzer."""
        from core.analyzer import generate_segment_coach_insights

        insights = generate_segment_coach_insights(self.segments, self.name_a, self.name_b)
        self.coach_text.setHtml("<br>".join(insights))


