    def _on_ai_analysis_clicked(self):
        """Avvia l'analisi IA in background tramite Ollama."""
        if not self.segments:
            QMessageBox.information(
                self, "Analisi IA", "Nessun segmento comune da analizzare."
            )
            return
        if self.track_a is None or self.track_b is None:
            QMessageBox.information(
                self,
                "Analisi IA",
                "Servono entrambe le tracce caricate per costruire il confronto.",
            )
            return

        model = self.ai_model_combo.currentText().strip()
        if not model:
            model = DEFAULT_MODEL
        base_url = os.environ.get("DUOTRACK_OLLAMA_URL", DEFAULT_BASE_URL)

        try:
            snapshot = build_comparison_snapshot(self.track_a, self.track_b, self.segments)
        except Exception as exc:  # noqa: BLE001
            QMessageBox.warning(
                self, "Analisi IA", f"Impossibile preparare i dati di confronto: {exc}"
            )
            return

        self.ai_button.setEnabled(False)
        self.ai_status_label.setText("Analisi in corso… (10–60 s)")
        self.ai_text.setPlainText("")

        worker = _AIAnalysisWorker(
            snapshot,
            self.name_a,
            self.name_b,
            self.segments,
            model,
            base_url,
            timeout=1800.0,
        )
        worker.signals.finished.connect(self._on_ai_finished)
        worker.signals.finished.connect(
            lambda *_args, w=worker: _WorkerKeeper.release(w)
        )
        _WorkerKeeper.track(worker)
        QThreadPool.globalInstance().start(worker)

