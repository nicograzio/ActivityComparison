def _format_timestamp(timestamp):
    """Format a timestamp to HH:MM:SS or N/A."""
    if timestamp is None:
        return "N/A"
    try:
        return timestamp.strftime("%H:%M:%S")
    except Exception:
        return "N/A"


def _get_speed_kmh(point):
    """Return speed in km/h from a track point, or None."""
    speed = getattr(point, "speed", None)
    if isinstance(speed, (int, float)) and speed >= 0:
        return float(speed * 3.6)
    return None


def _format_duration(seconds, decimals=0):
    """Format a duration in seconds to MM:SS or HH:MM:SS, with optional decimals."""
    if seconds is None:
        return "N/A"
    total = float(seconds)
    hours = int(total) // 3600
    minutes = (int(total) % 3600) // 60
    if decimals and decimals > 0:
        secs = total % 60
        fmt = f"{{:0{2 + decimals + 1}.{decimals}f}}"
        if hours > 0:
            return f"{hours}:{minutes:02d}:{fmt.format(secs)}"
        return f"{minutes}:{fmt.format(secs)}"
    secs = int(total) % 60
    if hours > 0:
        return f"{hours}:{minutes:02d}:{secs:02d}"
    return f"{minutes}:{secs:02d}"


def _format_pace(avg_speed_kmh):
    """Format average speed in km/h to min/km pace string."""
    if avg_speed_kmh is None or avg_speed_kmh <= 0:
        return "N/A"
    pace_min_per_km = 60.0 / avg_speed_kmh
    minutes = int(pace_min_per_km)
    seconds = int(round((pace_min_per_km - minutes) * 60))
    if seconds >= 60:
        minutes += 1
        seconds -= 60
    return f"{minutes}'{seconds:02d}\""


def _get_track_duration(track):
    """Calcola la durata in secondi di una traccia (dal primo all'ultimo punto)."""
    if not track or not hasattr(track, 'points') or not track.points:
        return None
    first_ts = getattr(track.points[0], 'timestamp', None)
    last_ts = getattr(track.points[-1], 'timestamp', None)
    if first_ts and last_ts:
        try:
            return (last_ts - first_ts).total_seconds()
        except Exception:
            return None
    return None


class _WorkerKeeper:
    """Mantiene vivi i riferimenti Python dei worker finché non completano.

    ``QThreadPool`` detiene solo il riferimento C++ del QRunnable: se il
    wrapper Python (e con esso l'oggetto dei segnali) viene raccolto dal GC
    mentre il thread è ancora in esecuzione, la successiva ``emit`` crasha
    con "wrapped C/C++ object has been deleted".
    """

    _instances = set()

    @classmethod
    def track(cls, worker: QRunnable) -> None:
        """Registra un worker come in esecuzione."""
        cls._instances.add(worker)

    @classmethod
    def release(cls, worker: QRunnable) -> None:
        """Rilascia il worker a lavoro ultimato."""
        cls._instances.discard(worker)


class _WorkerSignals(QObject):
    """Segnali scambiati tra i thread di lavoro e la GUI."""

    # (kind, text) con kind in {"ai", "offline", "error"}
    finished = pyqtSignal(str, str)
    models_loaded = pyqtSignal(list)


class _AIAnalysisWorker(QRunnable):
    """Esegue la generazione del report IA fuori dal thread della GUI."""

    def __init__(self, snapshot, name_a, name_b, segments, model, base_url, timeout=1800.0):
        super().__init__()
        self.signals = _WorkerSignals()
        self._snapshot = snapshot
        self._name_a = name_a
        self._name_b = name_b
        self._segments = segments
        self._model = model
        self._base_url = base_url
        self._timeout = timeout

    @pyqtSlot()
    def run(self):
        try:
            report = generate_ai_comparison(
                self._snapshot,
                self._name_a,
                self._name_b,
                model=self._model,
                base_url=self._base_url,
                timeout=self._timeout,
            )
            self.signals.finished.emit("ai", report)
        except OllamaUnavailableError as exc:
            fallback = generate_offline_fallback_report(
                self._segments, self._name_a, self._name_b, str(exc)
            )
            self.signals.finished.emit("offline", fallback)
        except Exception as exc:  # noqa: BLE001
            log.exception("Analisi IA fallita inaspettatamente")
            self.signals.finished.emit("error", str(exc))


class _AIAgentWorker(QRunnable):
    """Esegue il loop agentico di tool-calling fuori dal thread della GUI."""

    def __init__(self, snapshot, name_a, name_b, segments, model, base_url,
                 on_highlight=None, timeout=1800.0):
        super().__init__()
        self.signals = _WorkerSignals()
        self._snapshot = snapshot
        self._name_a = name_a
        self._name_b = name_b
        self._segments = segments
        self._model = model
        self._base_url = base_url
        self._on_highlight = on_highlight
        self._timeout = timeout

    @pyqtSlot()
    def run(self):
        try:
            report, transcript = run_agentic_comparison(
                self._snapshot,
                self._name_a,
                self._name_b,
                self._segments,
                model=self._model,
                base_url=self._base_url,
                timeout=self._timeout,
                on_highlight=self._on_highlight,
            )
            if transcript:
                steps = "\n".join(
                    f"- `{step['tool']}` {json.dumps(step['args'], ensure_ascii=False, default=str)}"
                    for step in transcript
                )
                report = f"{report}\n\n---\n**Strumenti usati dall'agente:**\n{steps}"
            self.signals.finished.emit("ai", report)
        except OllamaUnavailableError as exc:
            fallback = generate_offline_fallback_report(
                self._segments, self._name_a, self._name_b, str(exc)
            )
            self.signals.finished.emit("offline", fallback)
        except Exception as exc:  # noqa: BLE001
            log.exception("Agente IA fallito inaspettatamente")
            self.signals.finished.emit("error", str(exc))


class _OllamaModelsWorker(QRunnable):
    """Recupera i modelli locali disponibili senza bloccare la GUI."""

    def __init__(self, base_url, timeout=3.0):
        super().__init__()
        self.signals = _WorkerSignals()
        self._base_url = base_url
        self._timeout = timeout

    @pyqtSlot()
    def run(self):
        try:
            models = list_local_models(self._base_url, timeout=self._timeout)
        except OllamaUnavailableError:
            models = []
        self.signals.models_loaded.emit(models)


